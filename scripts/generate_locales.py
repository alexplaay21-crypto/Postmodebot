def main():
    os.makedirs(LOCALES_DIR, exist_ok=True)
    keys_reference = None
    for lang, data in TRANSLATIONS.items():
        if keys_reference is None:
            keys_reference = set(data.keys())
        else:
            missing = keys_reference - set(data.keys())
            extra = set(data.keys()) - keys_reference
            if missing or extra:
                raise SystemExit(f"[{lang}] key mismatch — missing={missing} extra={extra}")

        path = os.path.join(LOCALES_DIR, f"{lang}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
